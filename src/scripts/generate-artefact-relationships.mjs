// Generates config/artefact-relationships.json — a machine-readable map of
// which artefacts are derived from which, so the Apply Changes workflow can
// cascade an edit to a source catalogue into the artefacts derived from it
// (e.g. editing BUS-PRO must regenerate BUS-BPM; editing BUS-CAP must
// regenerate BUS-BCM and the matrices built on it).
//
// The data is the inverse of the `relatedTo` graph in src/lib/artefacts.js.
// We read that file as text and extract the structural ARTEFACTS_BASE literal,
// avoiding the app's i18n/JSON import path (which needs Vite to resolve).
//
//   node src/scripts/generate-artefact-relationships.mjs
//
import { readFileSync, writeFileSync } from 'fs'
import { fileURLToPath } from 'url'
import { dirname, resolve } from 'path'

const __dirname = dirname(fileURLToPath(import.meta.url))
const REPO = resolve(__dirname, '../..')

const src = readFileSync(resolve(REPO, 'src/lib/artefacts.js'), 'utf8')
const start = src.indexOf('const ARTEFACTS_BASE = [')
const end = src.indexOf('export const ARTEFACTS = ARTEFACTS_BASE')
if (start < 0 || end < 0) throw new Error('Could not locate ARTEFACTS_BASE in artefacts.js')
const literal = src.slice(src.indexOf('[', start), src.lastIndexOf(']', end) + 1)
// The literal is plain object/array syntax — evaluate it in isolation.
const ARTEFACTS = new Function(`return ${literal}`)()

const byId = Object.fromEntries(ARTEFACTS.map((a) => [a.id, a]))
const slim = (id) => ({
  id,
  name: byId[id]?.name,
  format: byId[id]?.format,
  diagramType: byId[id]?.diagramType,
})

// For each artefact, the artefacts that declare themselves derived-from it —
// these must be regenerated when the source changes.
const relationships = {}
for (const a of ARTEFACTS) {
  const derives = ARTEFACTS.filter((b) =>
    (b.relatedTo ?? []).some((r) => r.artefactId === a.id && r.relationship === 'derived-from')
  ).map((b) => slim(b.id))
  const derivedFrom = (a.relatedTo ?? [])
    .filter((r) => r.relationship === 'derived-from')
    .map((r) => slim(r.artefactId))
  if (derives.length || derivedFrom.length) {
    relationships[a.id] = {
      name: a.name,
      format: a.format,
      ...(a.diagramType && { diagramType: a.diagramType }),
      derives, // regenerate these when this artefact changes
      'derived-from': derivedFrom,
    }
  }
}

const out = {
  description:
    'Artefact derivation map (inverse of the relatedTo graph in the registry). When an artefact changes, the entries in its `derives` list are generated from it and must be regenerated to stay in sync. Generated by src/scripts/generate-artefact-relationships.mjs.',
  relationships,
}

writeFileSync(
  resolve(REPO, 'config/artefact-relationships.json'),
  JSON.stringify(out, null, 4) + '\n'
)
const total = Object.values(relationships).reduce((n, r) => n + r.derives.length, 0)
console.log(
  `wrote config/artefact-relationships.json — ${Object.keys(relationships).length} artefacts, ${total} derivation edges`
)
